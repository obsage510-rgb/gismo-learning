-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT,
  school TEXT DEFAULT 'Gismo Academy',
  reg_no TEXT DEFAULT '',
  disability TEXT DEFAULT 'None',
  role TEXT DEFAULT 'student',
  quizzes_passed INTEGER DEFAULT 0,
  last_login_date TEXT,
  current_streak INTEGER DEFAULT 0,
  preferred_learning_mode TEXT DEFAULT 'visual'
);

-- 2. Notes Table
CREATE TABLE IF NOT EXISTS public.notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  content TEXT,
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Textbooks / Courses Table
CREATE TABLE IF NOT EXISTS public.textbooks (
  id TEXT PRIMARY KEY,
  title TEXT,
  meta TEXT,
  image TEXT,
  descriptor TEXT,
  content TEXT,
  quiz_q TEXT,
  quiz_a TEXT,
  user_id BIGINT DEFAULT NULL
);

-- 4. Uploaded Files Metadata Table
CREATE TABLE IF NOT EXISTS public.files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  filename TEXT,
  filepath TEXT
);

-- 5. Homework / Assignments Table
CREATE TABLE IF NOT EXISTS public.homework (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT,
  description TEXT,
  student_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  status TEXT DEFAULT 'pending',
  submission_file TEXT,
  submission_filename TEXT,
  submission_date TIMESTAMPTZ
);

-- 6. AI Tutor Chats Table
CREATE TABLE IF NOT EXISTS public.chats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  role TEXT,
  content TEXT,
  session_id TEXT DEFAULT 'default',
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Quizzes Table
CREATE TABLE IF NOT EXISTS public.quizzes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  subject TEXT,
  created_by TEXT DEFAULT 'teacher',
  assigned_to TEXT DEFAULT 'all',
  questions TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Quiz Submissions Table
CREATE TABLE IF NOT EXISTS public.quiz_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id BIGINT REFERENCES public.quizzes(id) ON DELETE CASCADE,
  student_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  student_username TEXT,
  score INTEGER,
  total INTEGER,
  percentage INTEGER,
  answers TEXT,
  submitted_at TIMESTAMPTZ DEFAULT NOW()
);

-- Reload PostgREST schema cache so tables are immediately accessible via API
NOTIFY pgrst, 'reload schema';
